import math
import networkx as nx


# ============================================================
# PRIORITY CALCULATION
# ============================================================

def calculate_priority(
    exposure,
    vulnerability,
    accessibility,
    time_to_critical=None,
    cascade_severity=0
):
    """
    Calculate rescue priority for a village.

    Higher score = higher rescue priority.

    Inputs:
        exposure:
            Environmental/disaster exposure, expected 0 to 1.

        vulnerability:
            Village vulnerability, expected 0 to 1.

        accessibility:
            1.0 = easy to reach
            0.0 = very difficult/inaccessible

        time_to_critical:
            Estimated simulation steps until critical threshold.
            Lower time means greater urgency.

        cascade_severity:
            Severity generated by the cascading disaster engine.
    """

    exposure = max(0.0, min(float(exposure), 1.0))
    vulnerability = max(0.0, min(float(vulnerability), 1.0))
    accessibility = max(0.0, min(float(accessibility), 1.0))

    # --------------------------------------------------------
    # Exposure contribution
    # --------------------------------------------------------

    exposure_score = exposure * 35

    # --------------------------------------------------------
    # Vulnerability contribution
    # --------------------------------------------------------

    vulnerability_score = vulnerability * 30

    # --------------------------------------------------------
    # Accessibility contribution
    #
    # Poor accessibility increases priority.
    # --------------------------------------------------------

    accessibility_score = (1.0 - accessibility) * 15

    # --------------------------------------------------------
    # Time-to-critical contribution
    # --------------------------------------------------------

    if time_to_critical is None:
        urgency_score = 0

    elif time_to_critical <= 0:
        urgency_score = 15

    elif time_to_critical <= 2:
        urgency_score = 13

    elif time_to_critical <= 5:
        urgency_score = 10

    elif time_to_critical <= 10:
        urgency_score = 6

    else:
        urgency_score = 2

    # --------------------------------------------------------
    # Cascading disaster contribution
    # --------------------------------------------------------

    cascade_score = min(
        max(float(cascade_severity), 0.0) / 20.0,
        1.0
    ) * 5

    priority = (
        exposure_score
        + vulnerability_score
        + accessibility_score
        + urgency_score
        + cascade_score
    )

    return round(
        max(0.0, min(priority, 100.0)),
        2
    )


def get_priority_level(priority):
    """
    Convert priority score into a human-readable level.
    """

    if priority >= 75:
        return "CRITICAL"

    elif priority >= 50:
        return "HIGH"

    elif priority >= 25:
        return "MEDIUM"

    else:
        return "LOW"


# ============================================================
# DISTANCE
# ============================================================

def haversine_distance(
    lat1,
    lon1,
    lat2,
    lon2
):
    """
    Calculate distance between two GPS coordinates.

    Returns:
        Distance in kilometers.
    """

    earth_radius = 6371.0

    lat1 = math.radians(lat1)
    lon1 = math.radians(lon1)

    lat2 = math.radians(lat2)
    lon2 = math.radians(lon2)

    dlat = lat2 - lat1
    dlon = lon2 - lon1

    a = (
        math.sin(dlat / 2) ** 2
        +
        math.cos(lat1)
        * math.cos(lat2)
        * math.sin(dlon / 2) ** 2
    )

    a = max(0.0, min(a, 1.0))

    c = 2 * math.atan2(
        math.sqrt(a),
        math.sqrt(1 - a)
    )

    return round(
        earth_radius * c,
        2
    )


# ============================================================
# ROAD NETWORK
# ============================================================

def create_road_network(locations):
    """
    Create a NetworkX road graph.

    Nodes:
        Villages
        Shelters

    Edges:
        Roads from locations["roads"].

    The graph stores GPS coordinates so accessibility
    and travel time can be calculated later.
    """

    graph = nx.Graph()

    # --------------------------------------------------------
    # Add villages
    # --------------------------------------------------------

    for village in locations.get("villages", []):

        graph.add_node(
            village["name"],
            latitude=village["latitude"],
            longitude=village["longitude"],
            node_type="village"
        )

    # --------------------------------------------------------
    # Add shelters
    # --------------------------------------------------------

    for shelter in locations.get("shelters", []):

        graph.add_node(
            shelter["name"],
            latitude=shelter["latitude"],
            longitude=shelter["longitude"],
            node_type="shelter"
        )

    # --------------------------------------------------------
    # Add roads
    # --------------------------------------------------------

    for road in locations.get("roads", []):

        start_lat, start_lon = road["start"]
        end_lat, end_lon = road["end"]

        start_node = _find_nearest_node(
            graph,
            start_lat,
            start_lon
        )

        end_node = _find_nearest_node(
            graph,
            end_lat,
            end_lon
        )

        if (
            start_node is None
            or end_node is None
            or start_node == end_node
        ):
            continue

        distance = haversine_distance(
            graph.nodes[start_node]["latitude"],
            graph.nodes[start_node]["longitude"],
            graph.nodes[end_node]["latitude"],
            graph.nodes[end_node]["longitude"]
        )

        graph.add_edge(
            start_node,
            end_node,
            distance=distance,
            road_name=road["name"],
            accessible=True
        )

    return graph


def _find_nearest_node(
    graph,
    latitude,
    longitude
):
    """
    Find the graph node closest to a GPS coordinate.
    """

    nearest_node = None
    nearest_distance = float("inf")

    for node in graph.nodes:

        node_lat = graph.nodes[node]["latitude"]
        node_lon = graph.nodes[node]["longitude"]

        distance = haversine_distance(
            latitude,
            longitude,
            node_lat,
            node_lon
        )

        if distance < nearest_distance:
            nearest_distance = distance
            nearest_node = node

    return nearest_node


# ============================================================
# ACCESSIBILITY
# ============================================================

def calculate_accessibility(
    graph,
    village_name
):
    """
    Calculate village accessibility using the road graph.

    Returns:
        1.0 = highly accessible
        0.0 = inaccessible

    The calculation is based on:
        - Whether the village exists in the graph
        - Number of reachable neighboring nodes
        - Whether the village has a path to a shelter
        - Shortest path distance
    """

    if graph is None:
        return 0.0

    if village_name not in graph.nodes:
        return 0.0

    village_node = village_name

    # --------------------------------------------------------
    # Find shelter nodes
    # --------------------------------------------------------

    shelters = [
        node
        for node, data in graph.nodes(data=True)
        if data.get("node_type") == "shelter"
    ]

    if not shelters:
        return 0.5

    # --------------------------------------------------------
    # Check whether a path to a shelter exists.
    # --------------------------------------------------------

    reachable_paths = []

    for shelter in shelters:

        try:
            path_length = nx.shortest_path_length(
                graph,
                source=village_node,
                target=shelter,
                weight="distance"
            )

            reachable_paths.append(
                path_length
            )

        except nx.NetworkXNoPath:
            continue

    # No shelter can be reached.
    if not reachable_paths:
        return 0.0

    shortest_distance = min(
        reachable_paths
    )

    # --------------------------------------------------------
    # Distance score
    #
    # Shorter distance = better accessibility.
    # --------------------------------------------------------

    if shortest_distance <= 1:
        distance_score = 1.0

    elif shortest_distance <= 2:
        distance_score = 0.9

    elif shortest_distance <= 4:
        distance_score = 0.75

    elif shortest_distance <= 6:
        distance_score = 0.60

    elif shortest_distance <= 10:
        distance_score = 0.45

    else:
        distance_score = 0.30

    # --------------------------------------------------------
    # Connectivity score
    # --------------------------------------------------------

    degree = graph.degree(village_node)

    if degree >= 3:
        connectivity_score = 1.0

    elif degree == 2:
        connectivity_score = 0.85

    elif degree == 1:
        connectivity_score = 0.65

    else:
        connectivity_score = 0.30

    accessibility = (
        distance_score * 0.65
        + connectivity_score * 0.35
    )

    return round(
        max(0.0, min(accessibility, 1.0)),
        2
    )


# ============================================================
# RESCUE DEMAND
# ============================================================

def calculate_rescue_demand(
    population,
    exposure,
    vulnerability
):
    """
    Estimate number of people requiring rescue assistance.

    This is a prototype decision-support estimate.
    It is not an official evacuation model.
    """

    population = max(
        0,
        float(population)
    )

    exposure = max(
        0.0,
        min(float(exposure), 1.0)
    )

    vulnerability = max(
        0.0,
        min(float(vulnerability), 1.0)
    )

    # Base exposed population.
    exposed_population = (
        population * exposure
    )

    # Vulnerability increases the fraction
    # requiring assistance.
    vulnerability_factor = (
        0.5 + 0.5 * vulnerability
    )

    demand = (
        exposed_population
        * vulnerability_factor
    )

    return max(
        0,
        round(demand)
    )


# ============================================================
# REQUIRED RESOURCE TYPES
# ============================================================

def get_required_resource_types(
    exposure,
    accessibility,
    rescue_demand
):
    """
    Determine which resource types are appropriate.
    """

    required_types = []

    exposure = max(
        0.0,
        min(float(exposure), 1.0)
    )

    accessibility = max(
        0.0,
        min(float(accessibility), 1.0)
    )

    rescue_demand = max(
        0,
        float(rescue_demand)
    )

    if rescue_demand <= 0:
        return required_types

    # Boats are particularly useful when access is poor.
    if (
        accessibility < 0.50
        or exposure >= 0.75
    ):
        required_types.append("Boat")

    # Rescue teams are generally useful.
    required_types.append(
        "Rescue Team"
    )

    # Ambulances become important for
    # high-risk/high-demand areas.
    if (
        exposure >= 0.60
        or rescue_demand >= 100
    ):
        required_types.append(
            "Ambulance"
        )

    return required_types


# ============================================================
# TRAVEL TIME
# ============================================================

def calculate_travel_time(
    distance_km,
    accessibility=1.0,
    base_speed_kmh=30
):
    """
    Estimate travel time.

    Lower accessibility reduces effective speed.

    Returns:
        Minutes.
    """

    distance_km = max(
        0.0,
        float(distance_km)
    )

    accessibility = max(
        0.10,
        min(float(accessibility), 1.0)
    )

    base_speed_kmh = max(
        5.0,
        float(base_speed_kmh)
    )

    effective_speed = (
        base_speed_kmh
        * accessibility
    )

    travel_hours = (
        distance_km
        / effective_speed
    )

    return round(
        travel_hours * 60,
        1
    )


# ============================================================
# RESOURCE RECOMMENDATION
# ============================================================

def recommend_resource(
    resources,
    required_types,
    village,
    locations,
    accessibility=1.0
):
    """
    Recommend the nearest suitable available resource.
    """

    candidates = []

    for resource in resources:

        if not resource.get(
            "available",
            False
        ):
            continue

        resource_type = resource.get(
            "type"
        )

        if (
            required_types
            and resource_type not in required_types
        ):
            continue

        source_name = resource.get(
            "location"
        )

        source = None

        for shelter in locations.get(
            "shelters",
            []
        ):

            if shelter["name"] == source_name:
                source = shelter
                break

        if source is None:
            continue

        distance = haversine_distance(
            source["latitude"],
            source["longitude"],
            village["latitude"],
            village["longitude"]
        )

        travel_time = calculate_travel_time(
            distance,
            accessibility
        )

        candidates.append({
            "resource": resource,
            "distance": distance,
            "travel_time": travel_time
        })

    if not candidates:
        return None

    candidates.sort(
        key=lambda item: item["travel_time"]
    )

    return candidates[0]


# ============================================================
# ALLOCATION SCORE
# ============================================================

def calculate_allocation_score(
    priority,
    accessibility,
    resource_capacity,
    rescue_demand,
    travel_time
):
    """
    Calculate suitability of a resource for a village.

    Higher score = better allocation.
    """

    priority_score = (
        min(max(priority, 0) / 100, 1)
        * 40
    )

    accessibility_score = (
        max(0, min(accessibility, 1))
        * 20
    )

    if rescue_demand > 0:

        capacity_ratio = min(
            resource_capacity
            / rescue_demand,
            1
        )

        capacity_score = (
            capacity_ratio * 20
        )

    else:
        capacity_score = 0

    travel_score = max(
        0,
        20 - min(
            max(travel_time, 0),
            20
        )
    )

    score = (
        priority_score
        + accessibility_score
        + capacity_score
        + travel_score
    )

    return round(
        max(0, min(score, 100)),
        2
    )


# ============================================================
# RESOURCE EFFICIENCY
# ============================================================

def calculate_resource_efficiency(
    allocated_resources,
    people_supported
):
    """
    Estimate resource utilization efficiency.

    Returns:
        Score from 0 to 100.
    """

    if allocated_resources <= 0:
        return 0

    people_supported = max(
        0,
        float(people_supported)
    )

    efficiency = (
        people_supported
        / allocated_resources
    )

    # Prototype normalization:
    # 10 people supported per resource = 100.
    score = (
        efficiency / 10
    ) * 100

    return round(
        max(0, min(score, 100)),
        2
    )


# ============================================================
# RESOURCE ALLOCATION
# ============================================================

def allocate_resources(
    villages,
    resources,
    graph,
    risk_score
):
    """
    Allocate limited resources to localized villages.

    This function matches the current PRAVAAH app.py call:

        allocate_resources(
            villages=localized_villages,
            resources=locations["resources"],
            graph=road_graph,
            risk_score=risk_score
        )

    Returns a flat list of allocation records because
    app.py expects fields such as:

        village
        resource
        resource_type
        capacity
        travel_time
        covered_people
        remaining_demand
        allocation_score
        status
    """

    allocations = []

    if not villages:
        return allocations

    if not resources:
        return allocations

    # --------------------------------------------------------
    # Work on copies so the original location data remains
    # unchanged.
    # --------------------------------------------------------

    available_resources = []

    for resource in resources:

        copied_resource = resource.copy()

        if copied_resource.get(
            "available",
            False
        ):
            available_resources.append(
                copied_resource
            )

    # --------------------------------------------------------
    # Prepare village records.
    # --------------------------------------------------------

    village_records = []

    for village in villages:

        exposure = village.get(
            "exposure",
            0
        )

        vulnerability = village.get(
            "vulnerability",
            0
        )

        population = village.get(
            "population",
            0
        )

        accessibility = village.get(
            "accessibility",
            None
        )

        # If app.py has not calculated accessibility,
        # calculate it from the graph.
        if accessibility is None:

            accessibility = calculate_accessibility(
                graph,
                village["name"]
            )

        demand = village.get(
            "rescue_demand",
            None
        )

        if demand is None:

            demand = calculate_rescue_demand(
                population,
                exposure,
                vulnerability
            )

        priority = village.get(
            "priority",
            None
        )

        if priority is None:

            priority = calculate_priority(
                exposure=exposure,
                vulnerability=vulnerability,
                accessibility=accessibility
            )

        required_types = get_required_resource_types(
            exposure,
            accessibility,
            demand
        )

        village_records.append({
            "village": village,
            "name": village["name"],
            "exposure": exposure,
            "vulnerability": vulnerability,
            "population": population,
            "accessibility": accessibility,
            "demand": demand,
            "remaining_demand": demand,
            "priority": priority,
            "required_types": required_types
        })

    # --------------------------------------------------------
    # Highest priority villages are processed first.
    # --------------------------------------------------------

    village_records.sort(
        key=lambda item: item["priority"],
        reverse=True
    )

    # --------------------------------------------------------
    # Allocate resources.
    # --------------------------------------------------------

    for record in village_records:

        village = record["village"]

        # If there is no demand, don't allocate anything.
        if record["remaining_demand"] <= 0:

            allocations.append({
                "village": record["name"],
                "resource": "None",
                "resource_type": "None",
                "capacity": 0,
                "travel_time": None,
                "covered_people": 0,
                "remaining_demand": 0,
                "allocation_score": 0,
                "status": "No Demand"
            })

            continue

        best_resource = None
        best_score = -1
        best_travel_time = None

        # ----------------------------------------------------
        # Evaluate every available resource.
        # ----------------------------------------------------

        for resource in available_resources:

            if not resource.get(
                "available",
                False
            ):
                continue

            resource_type = resource.get(
                "type",
                ""
            )

            # If specific resource types are required,
            # prefer only those.
            if (
                record["required_types"]
                and resource_type
                not in record["required_types"]
            ):
                continue

            resource_location = resource.get(
                "location"
            )

            source_node = None

            # Find the resource's source node.
            if (
                graph is not None
                and resource_location in graph.nodes
            ):

                source_node = resource_location

            if source_node is None:
                continue

            # ------------------------------------------------
            # Calculate shortest road distance.
            # ------------------------------------------------

            try:

                distance = nx.shortest_path_length(
                    graph,
                    source=source_node,
                    target=record["name"],
                    weight="distance"
                )

            except (
                nx.NetworkXNoPath,
                nx.NodeNotFound
            ):

                continue

            travel_time = calculate_travel_time(
                distance,
                record["accessibility"]
            )

            capacity = resource.get(
                "capacity",
                0
            )

            score = calculate_allocation_score(
                priority=record["priority"],
                accessibility=record["accessibility"],
                resource_capacity=capacity,
                rescue_demand=record["remaining_demand"],
                travel_time=travel_time
            )

            if score > best_score:

                best_score = score
                best_resource = resource
                best_travel_time = travel_time

        # ----------------------------------------------------
        # No suitable resource found.
        # ----------------------------------------------------

        if best_resource is None:

            allocations.append({
                "village": record["name"],
                "resource": "None Available",
                "resource_type": "None",
                "capacity": 0,
                "travel_time": None,
                "covered_people": 0,
                "remaining_demand": record["remaining_demand"],
                "allocation_score": 0,
                "status": "Unmet Demand"
            })

            continue

        # ----------------------------------------------------
        # Allocate the selected resource.
        # ----------------------------------------------------

        capacity = best_resource.get(
            "capacity",
            0
        )

        covered_people = min(
            capacity,
            record["remaining_demand"]
        )

        remaining_demand = max(
            0,
            record["remaining_demand"]
            - covered_people
        )

        allocation_status = (
            "Allocated"
            if covered_people > 0
            else "Unmet Demand"
        )

        allocations.append({
            "village": record["name"],
            "resource": best_resource["name"],
            "resource_type": best_resource["type"],
            "capacity": capacity,
            "travel_time": best_travel_time,
            "covered_people": covered_people,
            "remaining_demand": remaining_demand,
            "allocation_score": round(
                best_score,
                2
            ),
            "status": allocation_status
        })

        # ----------------------------------------------------
        # Mark resource unavailable.
        # ----------------------------------------------------

        best_resource["available"] = False

    return allocations


# ============================================================
# ALLOCATION SUMMARY
# ============================================================

def summarize_allocation(
    allocation_results
):
    """
    Generate summary statistics for the dashboard.
    """

    if not allocation_results:

        return {
            "allocated_count": 0,
            "unmet_count": 0,
            "total_capacity": 0,
            "covered_people": 0,
            "remaining_demand": 0,
            "efficiency": 0
        }

    allocated_count = sum(
        1
        for item in allocation_results
        if item.get("status") == "Allocated"
    )

    unmet_count = sum(
        1
        for item in allocation_results
        if item.get("status") == "Unmet Demand"
    )

    total_capacity = sum(
        item.get("capacity", 0)
        for item in allocation_results
        if item.get("status") == "Allocated"
    )

    covered_people = sum(
        item.get("covered_people", 0)
        for item in allocation_results
    )

    remaining_demand = sum(
        item.get("remaining_demand", 0)
        for item in allocation_results
    )

    efficiency = calculate_resource_efficiency(
        allocated_count,
        covered_people
    )

    return {
        "allocated_count": allocated_count,
        "unmet_count": unmet_count,
        "total_capacity": total_capacity,
        "covered_people": covered_people,
        "remaining_demand": remaining_demand,
        "efficiency": efficiency
    }